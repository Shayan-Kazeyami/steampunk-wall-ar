'use strict'
// Collection interaction/focus contracts. Browser geometry and phone tracking are separate checks.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm')
const assert=require('node:assert/strict')
const {createRequire}=require('node:module')
const root=path.resolve(__dirname,'..')
const {JSDOM}=createRequire(path.join(root,'tools/verification/package.json'))('jsdom')
const source=fs.readFileSync(path.join(root,'src/ui/controller.js'),'utf8').replace('export function','function')
const spec=JSON.parse(fs.readFileSync(path.join(root,'src/shared/spec.json'),'utf8'))
const dom=new JSDOM('<main id="mount"></main>',{url:'https://test.invalid/',pretendToBeVisual:true})
const doc=dom.window.document,events=[]
const context=vm.createContext({window:dom.window,document:doc})
vm.runInContext(source+'\nglobalThis.create=createUIController',context)
const ui=context.create({mount:doc.querySelector('#mount'),spec,
  collection:[{id:'driveway',label:'Driveway',previewImage:'driveway.jpg'},
    {id:'garage-left',label:'Garage Left',previewImage:'garage.jpg'}],
  onStart:()=>events.push('start'),onPreviewWall:id=>events.push('preview:'+id),
  onClosePreview:()=>events.push('collection'),onHelpChange:open=>events.push('help:'+open),
  onSoundChange:value=>value,onMachineAction:()=>true,
})
const button=key=>doc.querySelector(`[data-control="${key}"]`)
const press=(element,key)=>element.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key,bubbles:true,cancelable:true}))
function run(){
  ui.setSoundAvailable(true)
  assert(button('sound').hidden,'landing has no disabled audio affordance')
  assert(!button('start').hidden)
  assert(button('preview').hidden,'the two artwork cards replace a generic preview button')
  assert.equal(doc.querySelectorAll('[data-preview-wall]').length,2)
  assert.equal(doc.querySelectorAll('select').length,0)
  doc.querySelector('[data-preview-wall="garage-left"]').click()
  assert.equal(events.pop(),'preview:garage-left')
  ui.setActiveWall('garage-left');ui.setMachineAvailable(false);ui.setState({state:'preview'})
  assert.equal(doc.querySelector('[data-preview-tab="garage-left"]').getAttribute('aria-pressed'),'true')
  assert(doc.querySelector('[aria-label="Machine interactions"]').hidden)
  assert(!button('exitPreview').hidden,'same-page preview retains a visible route back to the collection')
  button('exitPreview').focus();button('exitPreview').click()
  assert.equal(events.pop(),'collection')
  ui.setState({state:'landing'})
  assert.equal(doc.activeElement,button('start'),'focus leaves a hidden preview control')

  const help=doc.querySelector('.collection-help-button'),dialog=doc.querySelector('dialog'),close=doc.querySelector('.collection-help-close')
  help.focus();help.click()
  assert.equal(events.pop(),'help:true')
  assert(dialog.open && !dialog.hidden)
  assert.equal(doc.activeElement,close)
  assert.equal(doc.querySelectorAll('.collection-help-steps li').length,3)
  assert(doc.querySelector('.collection-help-steps').textContent.includes('central JZ Light Show sign and nearby machinery'))
  assert(doc.querySelector('.collection-help-steps').textContent.includes('clock and surrounding gears'))
  assert(!doc.querySelector('.collection-help-note').textContent.includes('step back'),'recovery does not always move the recognition details farther away')
  press(close,'Tab');assert.equal(doc.activeElement,close,'guide keeps keyboard focus inside')
  press(close,'Escape')
  assert(dialog.hidden && !dialog.open,'fallback dialog removes open on Escape')
  assert.equal(events.pop(),'help:false')
  assert.equal(doc.activeElement,help,'closing guide restores its trigger')
  help.click();dialog.dispatchEvent(new dom.window.Event('cancel',{cancelable:true}))
  assert(dialog.hidden && !dialog.open)
  assert.equal(events.pop(),'help:false')

  button('start').focus();ui.setState({state:'loading'})
  assert.equal(doc.querySelector('[role="status"]').getAttribute('aria-busy'),'true')
  assert(!doc.querySelector('.steampunk-ui__status').hidden)
  assert.equal(doc.activeElement,button('cancel'),'loading moves focus to a usable cancel action')
  assert(button('sound').hidden)
  ui.setState({state:'error',code:'CAMERA_DENIED',canRetry:true})
  assert(doc.querySelector('.steampunk-ui__status-text').textContent.includes('site settings'))
  assert(!button('retry').hidden && !button('preview').hidden)
  assert.equal(doc.querySelector('[role="status"]').getAttribute('aria-busy'),'false')
  assert.equal(doc.activeElement,button('retry'))
  ui.setState({state:'error',code:'ASSET_LOAD_FAILED',canRetry:true})
  assert(!doc.querySelector('.steampunk-ui__status-text').textContent.includes('demo'))
  ui.setActiveWall('driveway');ui.setMachineAvailable(true);ui.setState({state:'preview'})
  assert(!button('sound').hidden && !button('sound').disabled)
  assert(!doc.querySelector('[aria-label="Machine interactions"]').hidden)
  assert(!button('exitPreview').hidden)
  assert(!button('reset').hidden,'the shared Restart action remains available')
  assert.equal(doc.querySelectorAll('[data-machine-action="restart"]').length,0,'collection presents one restart action instead of duplicating it in the machine controls')
  doc.querySelector('[data-preview-tab="garage-left"]').click()
  assert.equal(events.pop(),'preview:garage-left')
  ui.setState({state:'searching'})
  assert(doc.querySelector('.steampunk-ui__helper').textContent.includes('central JZ Light Show sign'))
  assert(doc.querySelector('.steampunk-ui__helper').textContent.includes('Garage Left: frame the clock'))
  ui.setState({state:'lost'});assert(button('sound').hidden)
  assert(doc.querySelector('.steampunk-ui__helper').textContent.includes('sign or clock back into view'))
  help.click();assert.equal(events.pop(),'help:true')
  ui.dispose()
  assert.equal(events.pop(),'help:false','disposal releases a guide pause')
  assert.equal(doc.querySelector('.steampunk-ui'),null)
  dom.window.close()
  console.log('PASS: two-wall cards/previews, actionable state focus, guide Escape/cancel/focus/disposal hooks, clear loading/error states, active-only sound and machine controls')
}
if(require.main===module)run()
module.exports=run

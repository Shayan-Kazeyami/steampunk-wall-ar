'use strict'
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict')
const source=fs.readFileSync(path.resolve(__dirname,'../src/shared/field-session.js'),'utf8')
const context={console};vm.createContext(context)
vm.runInContext(source.replace('export function createFieldSession','function createFieldSession')+'\nglobalThis.createFieldSession=createFieldSession',context)
const {createFieldSession}=context
let time=0
const session=createFieldSession({now:()=>time,wallClock:()=> '2026-10-23T14:00:00.000Z',
  navigator:{userAgent:'Test browser',platform:'Fixture OS'},build:'fixture',wall:'driveway',
  maxSamples:3,sampleMs:1000})
let result=session.snapshot()
assert.equal(result.frameLoop.status,'NOT MEASURED');assert.equal(result.frameLoop.meanFps,null)
assert.equal(result.memory.status,'UNAVAILABLE');assert.equal(result.physicalChecks.printAlignment,'NOT MEASURED')
assert.equal(result.metadata.device,'NOT RECORDED')
session.frame(time)
for(let i=0;i<600;i++){time+=20;session.frame(time)}
result=session.snapshot()
assert.equal(result.frameLoop.meanFps,50)
assert.equal(result.frameLoop.intervals,600)
assert.equal(result.frameLoop.samples.length,3,'Rolling sample retention stays bounded')
assert(result.frameLoop.samples[0].elapsedMs<result.frameLoop.samples[2].elapsedMs,'Ring exported chronologically')
assert.equal(result.frameLoop.p95FrameMsLowerBound,20)
session.setActive(false);time+=10000;session.frame(time)
session.setActive(true);session.frame(time);time+=20;session.frame(time)
assert.equal(session.snapshot().frameLoop.meanFps,50,'Inactive time excluded explicitly')
time+=5000;session.frame(time)
assert.equal(session.snapshot().frameLoop.excludedGapMs,5000,'Unclassified long frame gaps excluded, reported')
session.frame(NaN);session.frame(time-1)
assert.equal(session.snapshot().frameLoop.invalidTimestamps,2)
assert(session.mark('assets-ready'));assert(!session.mark('invalid',-1))
for(let i=0;i<63;i++)assert(session.mark('step-'+i))
assert(!session.mark('too-many'),'Marks bounded')
assert(session.mark('assets-ready'),'Known marks can update at capacity')
assert(!session.sampleMemory({usedJSHeapSize:NaN,totalJSHeapSize:2,jsHeapSizeLimit:3}))
assert(session.sampleMemory({usedJSHeapSize:1,totalJSHeapSize:2,jsHeapSizeLimit:3}))
assert.equal(session.snapshot().memory.usedJSHeapSize,1)
result=session.snapshot();result.metadata.browser.userAgent='mutated';result.frameLoop.samples[0].fps=999
assert.equal(session.snapshot().metadata.browser.userAgent,'Test browser','Snapshots cannot mutate session')
assert.equal(session.snapshot().frameLoop.samples[0].fps,50)
session.stop();const stopped=JSON.parse(session.exportJSON());time+=3000;session.frame(time)
assert.equal(session.snapshot().elapsedMs,stopped.elapsedMs,'Stopped session remains fixed')
assert.equal(session.snapshot().frameLoop.intervals,stopped.frameLoop.intervals)
session.start({device:'Named phone supplied by operator',context:'USER_RECORDED_PHONE_SESSION'})
assert.equal(session.snapshot().frameLoop.status,'NOT MEASURED','Restart clears previous measurements')
assert.equal(session.snapshot().timings.status,'NOT MEASURED')
assert.equal(session.snapshot().metadata.device,'Named phone supplied by operator')
assert.equal(session.snapshot().physicalChecks.phoneTest,'NOT VERIFIED','Device label cannot fabricate acceptance')
console.log('PASS bounded frame-loop aggregates/ring, pauses/gaps, marks, observed heap, snapshot isolation, stop/restart and honest physical gates')
